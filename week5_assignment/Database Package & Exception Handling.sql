-- =========================================================
-- 1. Create ETL Package Schema
-- Purpose:
-- Create a dedicated schema to group all ETL procedures
-- and error logging objects.
-- =========================================================

CREATE SCHEMA IF NOT EXISTS etl_package;


-- =========================================================
-- 2. Create Error Logging Table
-- Purpose:
-- Store information about errors that occur during
-- the execution of ETL procedures.
-- =========================================================

CREATE TABLE etl_package.error_log (
    error_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    procedure_name VARCHAR(100),
    error_message TEXT,
    error_sqlstate VARCHAR(10),
    error_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


-- Check the error log table.
-- Initially, the table should contain no error records.
SELECT *
FROM etl_package.error_log;



-- =========================================================
-- 3. Create Error Logging Procedure
-- Purpose:
-- Provide a reusable procedure for recording errors
-- generated by other ETL procedures.
-- =========================================================

CREATE OR REPLACE PROCEDURE etl_package.log_error(
    p_procedure_name VARCHAR,
    p_error_message TEXT,
    p_error_sqlstate VARCHAR
)
LANGUAGE plpgsql
AS '
BEGIN

    -- Insert error details into the error log table.
    INSERT INTO etl_package.error_log (
        procedure_name,
        error_message,
        error_sqlstate
    )
    VALUES (
        p_procedure_name,
        p_error_message,
        p_error_sqlstate
    );

END;
';


